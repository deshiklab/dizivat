        await pg.goto(BASE + "/en/master/customers", wait_until="networkidle"); await pg.wait_for_timeout(500)
        await pg.screenshot(path=f"{OUT}/41_customers.png")
        await pg.get_by_role("button", name="New customer").first.click()
