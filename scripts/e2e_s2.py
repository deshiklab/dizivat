        # ── 9. Saved views live on the server ──────────────────────────
        await pg.goto(BASE + "/en/sales?mode=Foreign", wait_until="networkidle")
        await pg.get_by_role("button", name="Views").click(); await pg.get_by_role("menuitem", name="Save current view").click()
